export function getAllFragrances() {
  return HOUSES.flatMap(house =>
    house.fragrances.map(f => ({ ...f, houseName: house.name, houseId: house.id, houseOrigin: house.origin }))
  );
}

export function findFragrances(selectedNoteIds) {
  const all = getAllFragrances();
  if (!selectedNoteIds || !selectedNoteIds.length) {
    return all.slice(0, 6);
  }
  const scored = all.map(frag => {
    const matchedNotes = selectedNoteIds.filter(id => frag.noteIds.includes(id));
    return { ...frag, score: matchedNotes.length, matchedNotes };
  }).filter(f => f.score > 0);

  scored.sort((a, b) => b.score - a.score);
  return scored.length ? scored.slice(0, 6) : all.slice(0, 6);
}

export function getHouseById(id) {
  return HOUSES.find(h => h.id === id);
}
